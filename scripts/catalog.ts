import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export type Lang = 'he' | 'en';
export type AgeBand = '8-9' | '10-12';
export type Plan = 'free' | 'family';

export interface CatalogTrack {
  id: string;
  title: Record<Lang, string>;
  plan: Plan;
  minAgeBand: AgeBand;
}

export interface CatalogLesson {
  id: string;
  track: string;
  position: number;
  title: Record<Lang, string>;
}

export interface Catalog {
  tracks: CatalogTrack[];
  lessons: CatalogLesson[];
}

export const catalogPath = fileURLToPath(new URL('../content/catalog.json', import.meta.url));

export function loadCatalog(): Catalog {
  return JSON.parse(readFileSync(catalogPath, 'utf8')) as Catalog;
}

/** SQL literal for a plain string (single quotes doubled). */
function sqlString(value: string): string {
  return `'${value.replaceAll("'", "''")}'`;
}

/** Idempotent upsert of the catalog into public.lessons. */
export function catalogToSeedSql(catalog: Catalog): string {
  const tracks = new Map(catalog.tracks.map((t) => [t.id, t]));
  const rows = catalog.lessons.map((lesson) => {
    const track = tracks.get(lesson.track);
    if (!track) throw new Error(`Lesson ${lesson.id} points at unknown track ${lesson.track}`);
    return `  (${sqlString(lesson.id)}, ${sqlString(lesson.track)}, ${lesson.position}, ${sqlString(track.minAgeBand)}, ${sqlString(track.plan)})`;
  });

  return [
    '-- Generated by scripts/build-seed.ts from content/catalog.json. Do not edit by hand.',
    'insert into public.lessons (id, track, position, min_age_band, plan) values',
    rows.join(',\n'),
    'on conflict (id) do update set',
    '  track = excluded.track,',
    '  position = excluded.position,',
    '  min_age_band = excluded.min_age_band,',
    '  plan = excluded.plan;',
    '',
  ].join('\n');
}
